#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_days_count_to_the_reyes() {
        assert_eq!(days_to_reyes(Fiesta::of_day(12, 12)), 25);
        assert_eq!(days_to_reyes(Fiesta::of_day(12, 31)), 6);
        assert_eq!(days_to_reyes(Fiesta::of_day(1, 1)), 5);
        assert_eq!(days_to_reyes(Fiesta::of_day(1, 2)), 4);
        assert_eq!(days_to_reyes(Fiesta::of_day(1, 6)), 0);
        assert_eq!(posada(Fiesta::of_day(12, 16)), 1);
        assert_eq!(posada(Fiesta::of_day(12, 24)), 9);
        assert_eq!(posada(Fiesta::of_day(12, 25)), 0);
        assert_eq!(posada(Fiesta::of_day(12, 15)), 0);
        assert_eq!(posada(Fiesta::NONE), 0);
    }

    #[test]
    fn the_songs_are_there_and_the_mundane_lines_are_in_order() {
        assert!(VILLANCICOS.len() >= 9);
        assert!(
            VILLANCICOS
                .iter()
                .all(|(t, l)| !t.is_empty() && l.len() >= 4 && l.iter().all(|s| !s.is_empty()))
        );
        // The first `mundane_es` plain lines are Spanish, the rest English.
        assert!(VOCAB.mundane_es < VOCAB.mundane.len());
        assert!(VOCAB.mundane[VOCAB.mundane_es].starts_with("pinata hung"));
        assert!(
            VOCAB
                .headlines
                .iter()
                .any(|h| h.contains("RASTREO DE LOS REYES MAGOS"))
        );
    }
}
