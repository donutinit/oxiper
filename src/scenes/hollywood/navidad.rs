/// Days left until the Reyes on January 6 (0 on the day itself, and after
/// it); 26 on December 12.
pub fn days_to_reyes(f: Fiesta) -> u32 {
    match f.month {
        12 => (31 - f.day.min(31) as u32) + 6,
        1 => 6u32.saturating_sub(f.day as u32),
        _ => 0,
    }
}

/// Which of the nine posadas it is (1 on December 16, 9 on the 24th), or 0
/// outside them.
pub fn posada(f: Fiesta) -> u8 {
    if f.is(Kind::Navidad) && f.month == 12 && (16..=24).contains(&f.day) {
        f.day - 15
    } else {
        0
    }
}

