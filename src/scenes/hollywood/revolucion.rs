#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn morse_is_morse() {
        assert_eq!(morse('s'), "...");
        assert_eq!(morse('O'), "---");
        assert_eq!(morse('a'), ".-");
        assert_eq!(morse('1'), ".----");
        assert_eq!(morse(' '), "");
        // Every letter and digit of the telegrams has a code, and codes
        // are distinct.
        let mut seen = std::collections::HashSet::new();
        for ch in ('A'..='Z').chain('0'..='9') {
            assert!(seen.insert(morse(ch)), "{ch}");
        }
        for (_, _, text) in TELEGRAMS {
            assert!(
                text.chars().all(|c| c == ' ' || !morse(c).is_empty()),
                "{text}"
            );
        }
    }

    #[test]
    fn the_archive_has_its_documents_and_the_line_its_stations() {
        assert!(DOCUMENTS[0].0.contains("SAN LUIS") && DOCUMENTS[0].1.contains("20 de noviembre"));
        assert!(DOCUMENTS.len() >= 6 && TELEGRAMS.len() >= 12 && STATIONS.len() >= 8);
        assert!(STATIONS.windows(2).all(|w| w[0].1 < w[1].1));
        assert!(
            SLOGANS
                .iter()
                .any(|s| s.0 == "TIERRA" && s.1 == "Y LIBERTAD")
        );
        assert!(VOCAB.mundane_es < VOCAB.mundane.len());
        assert!(VOCAB.mundane[VOCAB.mundane_es].starts_with("telegram received"));
    }
}
